# Boolean aur None - Hinglish Notes

# True aur False boolean values hain.
a = True
b = False
print(type(a))
print(type(b))

# and: dono conditions True honi chahiye.
print(a and b)

# or: kam se kam ek condition True honi chahiye.
print(a or b)

# not: value ko ulta karta hai.
print(not a)

# Boolean Python mein integer ki tarah behave kar sakta hai:
# True == 1 aur False == 0.
print(a + 1)
print(b + 1)

# None ka matlab hai: abhi koi value nahi hai.
value = None
print(value)
print(type(value))
